using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Meridian.Mapping.Generators.Models;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
namespace Meridian.Mapping.Generators.Emission;

internal static class MapperEmitter
{
    internal static void Emit(SourceProductionContext context, MapperModel model)
    {
        if (!model.CanGenerate) return;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        var usings = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var pair in model.Pairs)
        {
            if (pair.SourceNamespace is not null)
                usings.Add(pair.SourceNamespace);
            if (pair.DestinationNamespace is not null)
                usings.Add(pair.DestinationNamespace);
        }

        foreach (var u in usings)
            sb.AppendLine($"using {u};");
        if (usings.Count > 0)
            sb.AppendLine();

        var indent = "";
        if (model.Namespace is not null)
        {
            sb.Append("namespace ").Append(model.Namespace).AppendLine();
            sb.AppendLine("{");
            indent = "    ";
        }

        foreach (var containingType in model.ContainingTypes)
        {
            EmitTypeDeclarationOpen(sb, indent, containingType);
            indent += "    ";
        }

        EmitTypeDeclarationOpen(sb, indent, model.TargetType);
        indent += "    ";

        var structural = model.Pairs.Any(pair => pair.Options.Mode == 1 && pair.Constructor.IsSupported);
        if (structural) GeneratedContextEmitter.Emit(sb);
        for (var index = 0; index < model.Pairs.Length; index++)
        {
            var pair = model.Pairs[index];
            if (!pair.Constructor.IsSupported) continue;
            if (pair.Options.Mode == 0) EmitMapMethod(sb, indent, pair);
            if (structural) NestedMapperEmitter.Emit(sb, indent, pair, index);
            sb.AppendLine();
        }

        indent = indent.Substring(0, indent.Length - 4);
        EmitTypeDeclarationClose(sb, indent);

        for (var i = model.ContainingTypes.Length - 1; i >= 0; i--)
        {
            indent = indent.Substring(0, indent.Length - 4);
            EmitTypeDeclarationClose(sb, indent);
        }

        if (model.Namespace is not null)
            sb.AppendLine("}");

        var hint = SanitizeHintName(model.MetadataPath) + ".Meridian.g.cs";
        context.AddSource(hint, SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void EmitTypeDeclarationOpen(StringBuilder sb, string indent, TypeDeclarationInfo typeInfo)
    {
        sb.Append(indent);

        if (!string.IsNullOrWhiteSpace(typeInfo.Accessibility))
        {
            sb.Append(typeInfo.Accessibility).Append(' ');
        }

        if (!string.IsNullOrWhiteSpace(typeInfo.Modifiers))
        {
            sb.Append(typeInfo.Modifiers).Append(' ');
        }

        sb.Append("partial ")
            .Append(typeInfo.Keyword)
            .Append(' ')
            .Append(EscapeIdentifier(typeInfo.Name))
            .Append(typeInfo.TypeParameters)
            .AppendLine();

        foreach (var clause in typeInfo.ConstraintClauses)
        {
            sb.Append(indent).Append("    ").Append("where ").AppendLine(clause);
        }

        sb.Append(indent).AppendLine("{");
    }

    private static void EmitTypeDeclarationClose(StringBuilder sb, string indent)
    {
        sb.Append(indent).AppendLine("}");
    }

    private static void EmitMapMethod(StringBuilder sb, string indent, MapPairModel pair)
    {
        var srcFull = pair.SourceIdentity;
        var dstFull = pair.DestinationIdentity;
        var methodName = pair.Options.MethodName ?? "MapTo" + pair.DestinationName;

        sb.Append(indent).Append("/// <summary>Source-generated mapper emitted by Meridian. Maps ")
            .Append(pair.SourceName).Append(" to ").Append(pair.DestinationName).AppendLine(".</summary>");
        sb.Append(indent).Append("public static ").Append(dstFull)
            .Append(' ').Append(EscapeIdentifier(methodName)).Append('(').Append(srcFull).AppendLine(" source)");
        sb.Append(indent).AppendLine("{");
        if (pair.SourceCanBeNull) sb.Append(indent).AppendLine("    if (source is null) return default!;");
        ConstructionEmitter.Emit(sb, indent, pair);
        sb.Append(indent).AppendLine("    return result;");
        sb.Append(indent).AppendLine("}");
    }

    private static string EscapeIdentifier(string name)
    {
        return SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ||
            SyntaxFacts.GetContextualKeywordKind(name) != SyntaxKind.None ? "@" + name : name;
    }

    private static string SanitizeHintName(string metadataPath)
    {
        var sb = new StringBuilder(metadataPath.Length);
        foreach (var c in metadataPath)
        {
            sb.Append(char.IsLetterOrDigit(c) || c is '.' or '_' ? c : '_');
        }

        return sb.ToString();
    }

}
