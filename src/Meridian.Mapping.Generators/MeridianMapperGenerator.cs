using System.Linq;
using System.Text;
using Meridian.Mapping.Generators.Discovery;
using Meridian.Mapping.Generators.Emission;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Meridian.Mapping.Generators;

/// <summary>
/// Roslyn incremental source generator. For each consumer class annotated
/// with <c>[GenerateMapper(typeof(TSrc), typeof(TDst))]</c>, emits a
/// <c>partial</c> class body containing a typed
/// <c>public static TDst MapTo{TDst}(TSrc source)</c> method whose body
/// uses statically bound construction and member assignments.
/// </summary>
/// <remarks>
/// <para>
/// Supports legacy shallow member mapping and opt-in structural DTO construction,
/// plus explicit member renames, ignores and static methods. Runtime resolvers,
/// expression configuration and recursive graphs remain outside this subset.
/// </para>
/// <para>
/// Output is deterministic — property assignments are emitted in the
/// order they appear in the destination type's metadata, not a hashed
/// order — so diffs across generator runs only appear when the
/// destination type actually changes.
/// </para>
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class MeridianMapperGenerator : IIncrementalGenerator
{
    private const string AttributeNamespace = "Meridian.Mapping";
    private const string AttributeName = "GenerateMapperAttribute";
    private const string AttributeFullName = AttributeNamespace + "." + AttributeName;
    private const string AttributeSource = @"// <auto-generated/>
#nullable enable
namespace Meridian.Mapping
{
    internal enum GeneratedMappingMode { Legacy = 0, Structural = 1 }
    internal enum GeneratedConversionKind { CheckedNumeric = 0, InvariantParse = 1 }
    [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
    internal sealed class ConvertMapMemberAttribute : System.Attribute
    {
        public ConvertMapMemberAttribute(string destinationMember, GeneratedConversionKind kind) { DestinationMember = destinationMember; Kind = kind; }
        public string DestinationMember { get; }
        public GeneratedConversionKind Kind { get; }
        public System.Type? SourceType { get; set; }
        public System.Type? DestinationType { get; set; }
    }

    [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
    internal sealed class MapMemberAttribute : System.Attribute
    {
        public MapMemberAttribute(string destinationMember, string sourceMember) { DestinationMember = destinationMember; SourceMember = sourceMember; }
        public string DestinationMember { get; }
        public string SourceMember { get; }
        public System.Type? SourceType { get; set; }
        public System.Type? DestinationType { get; set; }
    }

    [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
    internal sealed class IgnoreMapMemberAttribute : System.Attribute
    {
        public IgnoreMapMemberAttribute(string destinationMember) { DestinationMember = destinationMember; }
        public string DestinationMember { get; }
        public System.Type? SourceType { get; set; }
        public System.Type? DestinationType { get; set; }
    }

    [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
    internal sealed class MapWithAttribute : System.Attribute
    {
        public MapWithAttribute(string destinationMember, System.Type converterType, string methodName) { DestinationMember = destinationMember; ConverterType = converterType; MethodName = methodName; }
        public string DestinationMember { get; }
        public System.Type ConverterType { get; }
        public string MethodName { get; }
        public System.Type? SourceType { get; set; }
        public System.Type? DestinationType { get; set; }
    }


    /// <summary>
    /// Marks a partial class as the target for a Meridian source-generated
    /// mapper. For each attribute on the class, the generator emits a
    /// typed <c>MapTo{TDestination}(TSource)</c> method inside the class.
    /// </summary>
    /// <remarks>
    /// Supports shallow members, explicit static methods and opt-in structural
    /// constructor binding. Runtime resolvers and expression configuration
    /// remain on the runtime <c>IMapper</c> API.
    /// </remarks>
    [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
    internal sealed class GenerateMapperAttribute : System.Attribute
    {
        public GenerateMapperAttribute(System.Type sourceType, System.Type destinationType)
        {
            SourceType = sourceType;
            DestinationType = destinationType;
        }

        public System.Type SourceType { get; }
        public System.Type DestinationType { get; }
        public GeneratedMappingMode Mode { get; set; } = GeneratedMappingMode.Legacy;
        public int MaxDepth { get; set; } = 64;
        public int MaxCollectionItems { get; set; } = 10000;
        public bool PreserveReferences { get; set; } = false;
        public bool AllowUndefinedEnumValues { get; set; } = false;
        public bool AllowNullCollections { get; set; } = false;
        public bool AllowNullDestinationValues { get; set; } = true;
        public bool GenerateResolver { get; set; } = false;
        public string? MethodName { get; set; } = null;
    }
}
";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // 1. Emit the attribute into the consumer's compilation so they
        //    don't have to reference anything extra beyond Meridian.Mapping.
        context.RegisterPostInitializationOutput(pi =>
            pi.AddSource("GenerateMapperAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

        // 2. Find every class declared partial that carries the attribute.
        var candidates = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeFullName,
                predicate: static (node, _) => node is ClassDeclarationSyntax c
                    && c.Modifiers.Any(m => m.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.PartialKeyword)),
                transform: static (ctx, cancellationToken) => MappingModelBuilder.Build(ctx, cancellationToken))
            .WithTrackingName("MapperModel")
            .Where(static model => model.Pairs.Length > 0)
            .Select(static (model, _) => model)
            .WithTrackingName("MapperOutput");

        var diagnostics = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeFullName,
                predicate: static (node, _) => node is ClassDeclarationSyntax c
                    && c.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword)),
                transform: static (ctx, cancellationToken) => MappingModelBuilder.BuildDiagnostics(ctx, cancellationToken))
            .SelectMany(static (items, _) => items)
            .WithTrackingName("MapperDiagnostics");
        context.RegisterSourceOutput(diagnostics, static (spc, diagnostic) => spc.ReportDiagnostic(diagnostic));

        // 3. Per candidate, emit the partial class body.
        context.RegisterSourceOutput(candidates, static (spc, target) => MapperEmitter.Emit(spc, target));
    }

}
